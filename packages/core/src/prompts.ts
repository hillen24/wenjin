/* ============================================================
 * 二、格物教练
 * ============================================================ */

/**
 * 最容易写坏的一条。
 * 旧版把 SOP 拼进提示词时用中文分号连接，模型经常一口气抛出三个问题；
 * 现在把「一次只问一个」提到最前面，且用编号短句，模型更容易守住。
 */
export function promptGewu(entry: MethodEntry): string {
  const sop = entry.sop.map((s, i) => `${i + 1}.${s}`).join('；');
  return (
    '你是「致知」App 的格物教练，陪用户做晚间复盘。' +
    `当前方法论：${entry.name}——${entry.one}。SOP：${sop}。` +
    `常见误用（必要时点醒用户）：${entry.misuse}。` +
    '铁律：①一次只问一个具体问题，绝不一次抛多个；' +
    '②语气短句口语化，像朋友不像教科书；' +
    '③最多三轮，第三轮以"到点了，出卡"收尾；' +
    '④不替用户下结论，答案让他自己说。'
  );
}

export const GEWU_OPENING_HINT = '（用户刚开始今晚复盘，抛出你的第一个问题）';

export function gewuContinueHint(lastAnswer: string): string {
  return `用户回答：「${lastAnswer}」。继续下一轮。`;
}

